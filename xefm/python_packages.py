"""Extra Python libraries declared in ``~/.xefm/requirements.txt`` (#664).

A library XeFM does not ship — one ``config.py`` imports, a Pillow plugin such
as ``pillow-heif``, ``rawpy`` for an ``IMAGE_DECODERS`` entry — has had one
supported route: install XeFM with uv or pipx and add it there. Every other
install had none. The Homebrew formula's venv has no pip of its own and is
rebuilt on every upgrade; the signed apps (DMG, cask, Store) cannot be added to
at all.

This module is the route that works for all of them, and it is declarative::

    ~/.xefm/requirements.txt         <- the user writes this, next to config.py
    ~/.xefm/site-packages/3.14/      <- generated by `sync`, never edited by hand
        .stamp                       <- what the directory was synced from

**Sync** runs pip — the interpreter XeFM runs on, so the ABI always matches —
with ``--target`` into a staging directory, then swaps that in whole. A line
deleted from the file therefore removes its package, which ``pip --target``
would not do on its own. The packages XeFM itself runs on win: they are passed
to pip as constraints pinned to their exact versions, then pruned from the
result, so the directory never holds a second Pillow. A requirement that
conflicts with them fails the sync, and the failure names the conflict.

**Load** appends the directory to ``sys.path`` with ``site.addsitedir`` at
startup. It is separate from ``~/.xefm/extensions/`` and is not purged on a
config reload, which is right for your own code and wrong for numpy.

**The startup check** is offline: it compares ``.stamp`` and nothing else, and
says when a sync is needed. It never syncs by itself, because syncing reaches
the network.
"""

from __future__ import annotations

import hashlib
import importlib
import importlib.metadata
import importlib.util
import json
import os
import platform
import re
import shlex
import shutil
import site
import subprocess
import sys
import tempfile
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable

from xefm.log_manager import getLogger


logger = getLogger("PyPackages")

REQUIREMENTS = "requirements.txt"
STAMP = ".stamp"
PYPI_PIP_JSON = "https://pypi.org/pypi/pip/json"


# --- where things live --------------------------------------------------------

def python_version() -> str:
    """``3.14`` — the directory a sync writes to is per minor version, because
    a C extension built for one does not load in another."""
    return f"{sys.version_info.major}.{sys.version_info.minor}"


def platform_tag() -> str:
    """Interpreter, OS and machine: what decides whether a compiled package in
    the directory can load here at all. ``~/.xefm`` travels with dotfiles, so
    the directory may have been synced on another machine."""
    return "-".join(filter(None, (sys.implementation.cache_tag, sys.platform,
                                  platform.machine().lower(),
                                  getattr(sys, "abiflags", ""))))


@dataclass
class Layout:
    home: Path = field(default_factory=lambda: Path.home() / ".xefm")
    version: str = field(default_factory=python_version)

    def __post_init__(self):
        # ConfigManager.config_dir is an xefm.path.Path, which is not a pathlib one.
        self.home = Path(str(self.home))

    @property
    def requirements(self) -> Path:
        return self.home / REQUIREMENTS

    @property
    def root(self) -> Path:
        return self.home / "site-packages"

    @property
    def target(self) -> Path:
        return self.root / self.version

    @property
    def staging(self) -> Path:
        """Where a sync builds the next directory. Left in place when the swap
        cannot happen yet (Windows, with one of the old packages loaded) and
        swapped in at the next start instead."""
        return self.root / f".{self.version}.new"

    @property
    def retired(self) -> Path:
        return self.root / f".{self.version}.old"

    @property
    def pip_cache(self) -> Path:
        """A downloaded pip wheel, for an interpreter that has neither pip nor
        ensurepip (the Windows app's embeddable CPython)."""
        return self.root / ".pip"


# --- what was asked for, and what XeFM already has ----------------------------

def read_requirements(layout: Layout) -> str:
    try:
        return layout.requirements.read_text(encoding="utf-8")
    except FileNotFoundError:
        return ""


def declares_anything(text: str) -> bool:
    """Whether a requirements file asks for anything — blank lines and
    comments alone do not."""
    return any(line.split("#", 1)[0].strip() for line in text.splitlines())


def normalize(name: str) -> str:
    """PEP 503: ``Pillow``, ``pillow`` and ``pil_low`` name one project."""
    return re.sub(r"[-_.]+", "-", name).lower()


def host_distributions(layout: Layout) -> dict[str, str]:
    """``{normalized name: version}`` for every distribution XeFM can import
    without the synced directory — what it ships with, or what the venv it was
    installed into holds. The first one on the path wins, as it would for an
    import."""
    own = str(layout.root.resolve())
    found: dict[str, str] = {}
    for dist in importlib.metadata.distributions():
        name, version = dist.metadata["Name"], dist.version
        if not name or not version:
            continue
        try:
            location = str(Path(dist.locate_file("")).resolve())
        except (OSError, TypeError):
            location = ""
        if location == own or location.startswith(own + os.sep):
            continue
        found.setdefault(normalize(name), version)
    return found


def _sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _host_digest(host: dict[str, str]) -> str:
    return _sha256("\n".join(f"{n}=={v}" for n, v in sorted(host.items())))


Extensions = dict[str, list[str]]


def extension_requirements(layout: Layout) -> Extensions:
    """``{extension id: [requirement, …]}`` from the enabled extension
    packages' ``requires.python_packages`` — synced with requirements.txt."""
    from xefm import extensions
    try:
        return extensions.python_requirements(extensions.Layout(layout.home))
    except Exception as e:
        logger.error(f"Could not read the extensions' Python packages: {e}")
        return {}


def make_stamp(requirements: str, host: dict[str, str],
               extensions: Extensions | None = None) -> dict:
    return {"requirements": _sha256(requirements), "host": _host_digest(host),
            "extensions": dict(sorted((extensions or {}).items())),
            "python": python_version(), "platform": platform_tag()}


def read_stamp(directory: Path) -> dict | None:
    try:
        return json.loads((directory / STAMP).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


# --- the startup check ----------------------------------------------------------

#: Nothing declared and nothing synced: the feature is not in use.
UNUSED = "unused"
#: The directory matches the file, this Python and XeFM's own packages.
IN_SYNC = "in-sync"
#: A sync is due; the directory (if any) is still loaded.
NEEDS_SYNC = "needs-sync"
#: The directory was synced for another platform and is not loaded.
FOREIGN = "foreign"


@dataclass
class Status:
    state: str
    reason: str = ""
    loaded: bool = False

    @property
    def message(self) -> str:
        if self.state == NEEDS_SYNC:
            return (f"Python packages need a sync: {self.reason}. Run Sync Python "
                    "Packages (Tools > Advanced), or `xefm deps sync` from a shell.")
        if self.state == FOREIGN:
            return (f"Python packages not loaded: {self.reason}. Run Sync Python "
                    "Packages (Tools > Advanced), or `xefm deps sync` from a shell.")
        return ""


def _changed_extensions(stamp: dict, extensions: Extensions) -> list[str]:
    synced = stamp.get("extensions") or {}
    return sorted(i for i in set(synced) | set(extensions)
                  if synced.get(i) != extensions.get(i))


def check(layout: Layout, host: dict[str, str] | None = None,
          extensions: Extensions | None = None) -> Status:
    """Compare the stamp with the file, the extensions' requirements, this
    Python and XeFM's own packages. Offline and cheap; says what is out of
    date, and never fixes it."""
    text = read_requirements(layout)
    if extensions is None:
        extensions = extension_requirements(layout)
    stamp = read_stamp(layout.target) if layout.target.is_dir() else None
    if stamp is None:
        if layout.target.is_dir():
            return Status(NEEDS_SYNC, f"{layout.target} has no {STAMP}", loaded=True)
        if not declares_anything(text) and not extensions:
            return Status(UNUSED)
        others = sorted(p.name for p in layout.root.glob("[0-9]*.[0-9]*") if p.is_dir())
        if others:
            return Status(NEEDS_SYNC, f"{layout.requirements} was synced for Python "
                          f"{', '.join(others)}, and XeFM now runs on {layout.version}")
        if declares_anything(text):
            return Status(NEEDS_SYNC, f"{layout.requirements} has not been synced yet")
        return Status(NEEDS_SYNC, "the extensions' Python packages have not been "
                      "synced yet")
    if stamp.get("platform") != platform_tag():
        return Status(FOREIGN, f"{layout.target} was synced for "
                      f"{stamp.get('platform')}, not {platform_tag()}")
    if stamp.get("requirements") != _sha256(text):
        return Status(NEEDS_SYNC, f"{layout.requirements} changed since the last sync",
                      loaded=True)
    changed = _changed_extensions(stamp, extensions)
    if changed:
        return Status(NEEDS_SYNC, "the Python packages of extension "
                      f"{', '.join(changed)} changed since the last sync", loaded=True)
    if host is None:
        host = host_distributions(layout)
    if stamp.get("host") != _host_digest(host):
        return Status(NEEDS_SYNC, "XeFM's own packages changed since the last sync "
                      "(an upgrade, or another XeFM install sharing ~/.xefm)", loaded=True)
    return Status(IN_SYNC, loaded=True)


def synced_for(layout: Layout, ext_id: str, wanted: list[str]) -> bool:
    """Whether the last sync installed exactly ``wanted`` for this extension,
    on this platform — so its imports will find them. Offline: the stamp is
    the record. A package the host already had counts too: the sync pruned it
    because XeFM's own copy is what gets imported."""
    stamp = read_stamp(layout.target) if layout.target.is_dir() else None
    return (stamp is not None and stamp.get("platform") == platform_tag()
            and (stamp.get("extensions") or {}).get(ext_id) == list(wanted))


# --- loading ----------------------------------------------------------------------

def _swap_in(layout: Layout) -> bool:
    """Replace the target directory with the staged one. False if the old one
    cannot be moved yet — on Windows, a loaded ``.pyd`` holds its directory —
    in which case nothing has changed and the staged directory waits."""
    shutil.rmtree(layout.retired, ignore_errors=True)
    had_target = layout.target.exists()
    try:
        if had_target:
            os.replace(layout.target, layout.retired)
    except OSError as e:
        logger.info(f"Could not replace {layout.target} while it is in use: {e}")
        return False
    try:
        os.replace(layout.staging, layout.target)
    except OSError as e:
        logger.error(f"Could not move {layout.staging} into place: {e}")
        if had_target:
            os.replace(layout.retired, layout.target)
        return False
    shutil.rmtree(layout.retired, ignore_errors=True)
    return True


def activate(layout: Layout | None = None) -> Status:
    """At startup: finish a sync that was waiting for a restart, append the
    directory to ``sys.path`` unless it was synced for another platform, and
    say whether a sync is due. Safe to call again on a config reload."""
    layout = layout or Layout()
    if layout.staging.is_dir():
        if read_stamp(layout.staging) is None:
            # An interrupted sync: never swap in a half-built directory.
            shutil.rmtree(layout.staging, ignore_errors=True)
        elif str(layout.target.resolve()) not in sys.path:
            _swap_in(layout)
    try:
        status = check(layout)
    except Exception as e:
        logger.error(f"Could not check {layout.target}: {e}")
        return Status(UNUSED)
    if status.loaded:
        _add_to_path(layout.target)
    return status


def _add_to_path(directory: Path) -> None:
    resolved = str(directory.resolve())
    if resolved not in sys.path:
        # Appended, like ~/.xefm/extensions: XeFM's own packages stay first.
        # addsitedir also runs the directory's .pth files, which some packages
        # (pywin32 among them) need in order to import at all.
        site.addsitedir(resolved)
    importlib.invalidate_caches()


# --- finding pip -------------------------------------------------------------------

class SyncError(Exception):
    """A sync that did not complete. The target directory is untouched."""


Runner = Callable[..., "subprocess.CompletedProcess"]
Opener = Callable[[str], bytes]


def _no_window() -> dict:
    from xefm.external_programs import SUBPROCESS_NO_WINDOW
    return SUBPROCESS_NO_WINDOW


def _bundled_pip_wheel() -> Path | None:
    """The pip wheel ensurepip carries. Run straight from the wheel, which pip
    supports, it needs no install anywhere."""
    spec = importlib.util.find_spec("ensurepip")
    if spec is None or not spec.origin:
        return None
    wheels = sorted((Path(spec.origin).parent / "_bundled").glob("pip-*.whl"))
    return wheels[-1] if wheels else None


def _download_pip_wheel(layout: Layout, opener: Opener) -> Path:
    """The latest pip wheel from PyPI, checked against the digest PyPI lists
    for it, kept under ``site-packages/.pip`` so this happens once."""
    cached = sorted(layout.pip_cache.glob("pip-*.whl"))
    if cached:
        return cached[-1]
    try:
        info = json.loads(opener(PYPI_PIP_JSON))
        wheel = next(u for u in info["urls"]
                     if u.get("packagetype") == "bdist_wheel"
                     and u["filename"].endswith("-py3-none-any.whl"))
        payload = opener(wheel["url"])
    except (OSError, ValueError, KeyError, StopIteration) as e:
        raise SyncError(f"no pip here, and it could not be downloaded: {e}") from None
    if hashlib.sha256(payload).hexdigest() != wheel["digests"]["sha256"]:
        raise SyncError(f"the downloaded {wheel['filename']} does not match "
                        "the digest PyPI lists for it")
    layout.pip_cache.mkdir(parents=True, exist_ok=True)
    path = layout.pip_cache / wheel["filename"]
    path.write_bytes(payload)
    return path


def _urlopen(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def pip_command(python: str, layout: Layout, run: Runner = subprocess.run,
                opener: Opener = _urlopen) -> list[str]:
    """How to run pip on ``python``, best first: its own pip (pipx, the formula
    venv through Homebrew's), else the wheel ensurepip carries (the macOS app,
    a uv venv), else one downloaded from PyPI (the Windows app's embeddable
    CPython has neither)."""
    probe = run([python, "-m", "pip", "--version"], capture_output=True,
                stdin=subprocess.DEVNULL, **_no_window())
    if probe.returncode == 0:
        return [python, "-m", "pip"]
    wheel = _bundled_pip_wheel() or _download_pip_wheel(layout, opener)
    return [python, os.path.join(str(wheel), "pip")]


# --- sync ---------------------------------------------------------------------------

@dataclass
class SyncResult:
    installed: list[str]          # "name version", what the directory now holds
    pruned: list[str]             # names XeFM already provides, left out
    pending_restart: bool = False # staged; swapped in at the next start


def _prune(directory: Path, host: dict[str, str]) -> list[str]:
    """Remove from ``directory`` every distribution XeFM already has — pip
    put them there because ``--target`` resolves as if nothing were
    installed. The constraints made them the very same versions, so the
    host's copy is what would be imported anyway."""
    pruned = []
    root = directory.resolve()
    for dist in list(importlib.metadata.distributions(path=[str(directory)])):
        name = dist.metadata["Name"]
        if not name or normalize(name) not in host:
            continue
        dirs = set()
        for entry in dist.files or ():
            path = Path(dist.locate_file(entry)).resolve()
            # RECORD may name scripts outside the site directory ("../../bin");
            # never delete anything that is not inside it.
            if root not in path.parents:
                continue
            try:
                path.unlink()
            except FileNotFoundError:
                pass
            dirs.add(path.parent)
        info_dir = getattr(dist, "_path", None)
        if info_dir is not None:
            shutil.rmtree(info_dir, ignore_errors=True)
        for d in sorted(dirs, key=lambda p: len(p.parts), reverse=True):
            while d != root and root in d.parents:
                try:
                    d.rmdir()
                except OSError:
                    break
                d = d.parent
        pruned.append(name)
    return sorted(pruned, key=str.lower)


def _conflict_block(output: list[str]) -> list[str]:
    """pip's own account of a failed resolution: the indented lines under
    "The conflict is caused by:"."""
    lines, inside = [], False
    for line in output:
        if line.strip().startswith("The conflict is caused by"):
            inside, lines = True, []
        elif inside and line.startswith((" ", "\t")) and line.strip():
            lines.append(line.strip())
        else:
            inside = False
    return lines


def _attribute(line: str, extensions: Extensions) -> str:
    """``line`` with the extensions that asked for the project it names, so a
    conflict says whose requirement it is."""
    match = re.search(r"requested\s+(?:\(constraint\)\s+)?([A-Za-z0-9._-]+)", line)
    if not match or "(constraint)" in line:
        return line
    name = normalize(match.group(1))
    owners = [i for i, reqs in sorted(extensions.items())
              if any(normalize(re.match(r"\s*([A-Za-z0-9._-]+)", r).group(1)) == name
                     for r in reqs)]
    return f"{line} (extension {', '.join(owners)})" if owners else line


def sync(layout: Layout | None = None, python: str | None = None,
         log: Callable[[str], None] = lambda line: None,
         run: Runner = subprocess.run, popen=subprocess.Popen,
         opener: Opener = _urlopen,
         extensions: Extensions | None = None) -> SyncResult:
    """Bring the directory to match ``requirements.txt`` plus the enabled
    extensions' ``requires.python_packages``, resolved together so a clash
    between any two of them fails here rather than at import. pip's output
    goes to ``log`` a line at a time. Raises :class:`SyncError` and leaves the
    current directory as it was when anything fails."""
    layout = layout or Layout()
    if python is None:
        from xefm.external_programs import xefm_python as python
    text = read_requirements(layout)
    if extensions is None:
        extensions = extension_requirements(layout)
    declared = declares_anything(text) or any(extensions.values())
    if not declared and not layout.target.exists():
        return SyncResult([], [])
    host = host_distributions(layout)
    shutil.rmtree(layout.staging, ignore_errors=True)
    layout.staging.mkdir(parents=True)
    try:
        if declared:
            _pip_install(layout, python, host, extensions, log, run, popen, opener)
            pruned = _prune(layout.staging, host)
        else:
            pruned = []
        (layout.staging / STAMP).write_text(
            json.dumps(make_stamp(text, host, extensions), indent=2), encoding="utf-8")
    except BaseException:
        shutil.rmtree(layout.staging, ignore_errors=True)
        raise
    installed = sorted(
        (f"{d.metadata['Name']} {d.version}"
         for d in importlib.metadata.distributions(path=[str(layout.staging)])
         if d.metadata["Name"]), key=str.lower)
    # Swapped in even when nothing is declared: an empty directory replaces
    # the old one the same way, waiting for a restart if it has to.
    swapped = _swap_in(layout)
    if swapped and not declared:
        shutil.rmtree(layout.target, ignore_errors=True)
        try:
            layout.root.rmdir()
        except OSError:
            pass  # not empty: the downloaded pip, or another Python's directory
    elif swapped:
        _add_to_path(layout.target)
    return SyncResult(installed, pruned, pending_restart=not swapped)


def _include_line(path) -> str:
    """A requirements-file line that includes ``path``. pip splits the line
    with shlex: a Windows backslash would be read as an escape and dropped
    (#749), and a space would split the path. Forward slashes and quoting
    survive both."""
    return f"-r {shlex.quote(path.as_posix())}\n"


def _pip_install(layout, python, host, extensions, log, run, popen, opener) -> None:
    pip = pip_command(python, layout, run=run, opener=opener)
    with tempfile.TemporaryDirectory(prefix="xefm-deps-") as tmp:
        constraints = Path(tmp) / "host-constraints.txt"
        constraints.write_text("".join(f"{n}=={v}\n" for n, v in sorted(host.items())),
                               encoding="utf-8")
        # One file, one resolution: the user's own (by reference, so its
        # relative -r and paths keep meaning what they say) and every
        # extension's lines under a comment naming it.
        wanted = Path(tmp) / "requirements.txt"
        parts = []
        if declares_anything(read_requirements(layout)):
            parts.append(_include_line(layout.requirements))
        for ext_id, reqs in sorted(extensions.items()):
            parts.append(f"# extension {ext_id}\n" + "".join(f"{r}\n" for r in reqs))
        wanted.write_text("".join(parts), encoding="utf-8")
        argv = pip + ["install", "--target", str(layout.staging),
                      "--no-input", "--disable-pip-version-check",
                      "-r", str(wanted), "-c", str(constraints)]
        env = dict(os.environ)
        # The user's own pip settings must not redirect this install.
        for name in ("PIP_TARGET", "PIP_PREFIX", "PIP_USER", "PIP_REQUIRE_VIRTUALENV"):
            env.pop(name, None)
        logger.info(f"Running: {' '.join(argv)}")
        output: list[str] = []
        try:
            # cwd is ~/.xefm, so a relative path in requirements.txt means what
            # it says relative to the file.
            proc = popen(argv, cwd=str(layout.home), env=env,
                         stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                         stderr=subprocess.STDOUT, text=True, errors="replace",
                         **_no_window())
        except OSError as e:
            raise SyncError(f"could not run pip: {e}") from None
        for line in proc.stdout:
            line = line.rstrip("\n")
            output.append(line)
            log(line)
        proc.stdout.close()
        code = proc.wait()
    if code != 0:
        conflicts = [_attribute(line, extensions) for line in _conflict_block(output)]
        if any("(constraint)" in line for line in conflicts):
            raise SyncError("a requirement conflicts with a package XeFM itself "
                            "runs on, whose version wins: " + "; ".join(conflicts))
        if conflicts:
            raise SyncError("requirements conflict with each other: "
                            + "; ".join(conflicts))
        raise SyncError(f"pip exited with code {code}")
